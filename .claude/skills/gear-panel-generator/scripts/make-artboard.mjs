#!/usr/bin/env node
// Generate a standalone panel-only artboard from assets/app.css + assets/app.js + data/custom-amps.json.
//
// Usage (from the repo root):
//   node .claude/skills/gear-panel-generator/scripts/make-artboard.mjs <ampId> <OutName> \
//     --css-start '/* ---------- Mesa/Boogie TriAxis' --js-start '// Mesa/Boogie TriAxis:' \
//     --render "'<div class=\"cab txcab\">'+triaxisPanelHTML(def, as)+'</div>'"
//
// The panel CSS runs from --css-start to the next '/* ---------- ' banner; the panel JS runs
// from --js-start to the generic panel code ('// Generic panels'). The amp definition is kept in its own JSON
// block, separate from the markup. Output: artboards/<OutName>Mock.dc.html. The artboard is
// interactive (knobs, keys, switches, modes) but does no matching.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const [ampId, outName, ...rest] = process.argv.slice(2);
const opt = (name) => { const i = rest.indexOf('--' + name); return i >= 0 ? rest[i + 1] : null; };
const cssStart = opt('css-start'), jsStart = opt('js-start'), render = opt('render');
if (!ampId || !outName || !cssStart || !jsStart || !render) {
  console.error('Usage: make-artboard.mjs <ampId> <OutName> --css-start <banner> --js-start <comment> --render <JS expression using def, as>');
  process.exit(2);
}
const between = (text, start, endRe) => {
  const i = text.indexOf(start);
  if (i < 0) throw new Error('Not found in assets/app.css or assets/app.js: ' + start);
  const re = new RegExp(endRe, 'g'); re.lastIndex = i + start.length;
  const m = re.exec(text);
  return text.slice(i, m ? m.index : text.length);
};

const style = fs.readFileSync(path.join(ROOT, 'assets/app.css'), 'utf8');
const root = style.match(/:root\{[^}]*\}/)[0];
const shared = between(style, '/* ---------- amp: shared', '/\\* ---------- Marshall');
const jro = style.match(/\.jro\{[^}]*\}/)[0];
const panelCss = between(style, cssStart, '\\n/\\* ---------- ');
const script = fs.readFileSync(path.join(ROOT, 'assets/app.js'), 'utf8');
const panelJs = between(script, jsStart, '\\n(?:// Generic panels|function genericPanelHTML)');
// Shared helpers the panels use (whole functions, one-line or multi-line).
const fnSource = (n) => {
  const i = script.indexOf('\nfunction ' + n + '(');
  if (i < 0) throw new Error('Helper not found in assets/app.js: ' + n);
  const lineEnd = script.indexOf('\n', i + 1), line = script.slice(i + 1, lineEnd);
  return line.trimEnd().endsWith('}') ? line : script.slice(i + 1, script.indexOf('\n}\n', i) + 2);
};
const helpers = ['f1', 'nice', 'chName', 'available', 'esc', 'jattr', 'snap', 'chAttr', 'tip', 'posFor', 'leverSVG', 'togSVG', 'togHSVG', 'targetAttrs', 'targetId', 'jpToggle', 'faderInput'].map(fnSource).join('\n');
const amp = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/custom-amps.json'), 'utf8')).find((d) => d.id === ampId);
if (!amp) throw new Error('No custom amp with id ' + ampId);
const { match, parse, ...panelData } = amp; // build-only rules are not panel data

const out = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${amp.model} panel mock</title>
<!-- Generated by .claude/skills/gear-panel-generator/scripts/make-artboard.mjs from assets/app.css + assets/app.js; do not edit by hand. -->
<style>
${root}
html{color-scheme:dark}
body{margin:0;padding:24px 16px;background:var(--bg);color:var(--text);font-family:'IBM Plex Sans',ui-sans-serif,system-ui,sans-serif}
*{box-sizing:border-box} button,input{font:inherit;color:inherit} button{cursor:pointer}
button:focus-visible{outline:2px solid #f0b452;outline-offset:2px}
.sr{position:absolute;width:1px;height:1px;padding:0;margin:-1px;overflow:hidden;clip:rect(0 0 0 0);white-space:nowrap;border:0}
.board{display:flex;flex-direction:column;align-items:center;gap:10px} #panel{max-width:100%;display:flex;flex-direction:column}
.cap{font-size:12px;color:var(--muted)}
${shared}
${jro}
${panelCss}
</style>
</head>
<body>
<div class="board"><div id="panel"></div><p class="cap">${amp.brand} ${amp.model} — panel mock. Visual reference only — nothing here controls a physical amp.</p></div>
<script type="application/json" id="panel-data">${JSON.stringify(panelData).replace(/</g, '\\u003c')}</script>
<script>
'use strict';
const def = JSON.parse(document.getElementById('panel-data').textContent);
const as = JSON.parse(JSON.stringify(def.defaults));
${helpers}
${panelJs}
const C = (k) => def.controls.find(c => c.key === k);
function set(key, v){ if (key === '@channel') as.channel = v; else as.global[key] = v; draw(); }
function draw(){
  const f = document.activeElement && document.activeElement.id;
  document.getElementById('panel').innerHTML = ${render};
  if (f && document.getElementById(f)) document.getElementById(f).focus({preventScroll:true});
}
document.addEventListener('click', e => {
  const t = e.target.closest('[data-act]'); if (!t) return;
  if (t.dataset.act === 'channel') set('@channel', Number(t.dataset.n));
  else if (t.dataset.act === 'pick') set(t.dataset.key, JSON.parse(t.dataset.v));
  else if (t.dataset.act === 'cycle' && t.dataset.target === 'channel') { const ns = def.channels.map(c => c.n); set('@channel', ns[(ns.indexOf(as.channel) + 1) % ns.length]); }
  else if (t.dataset.act === 'cycle') { const c = C(t.dataset.key), i = c.options.findIndex(o => o.v === as.global[c.key]); set(c.key, c.options[(i + 1) % c.options.length].v); }
});
document.addEventListener('input', e => { const t = e.target; if (t.matches('input[type=range][data-ctrl]')) set(t.dataset.ctrl, snap(C(t.dataset.ctrl), parseFloat(t.value))); });
let drag = null;
document.addEventListener('pointerdown', e => { const t = e.target.closest('[data-drag]'); if (!t) return; e.preventDefault(); drag = {c:C(t.dataset.ctrl), y:e.clientY, v:as.global[t.dataset.ctrl]}; });
window.addEventListener('pointermove', e => { if (!drag) return; const c = drag.c, nv = snap(c, drag.v + (drag.y - e.clientY)/14 * (c.max - c.min)/10); if (nv !== as.global[c.key]) set(c.key, nv); });
window.addEventListener('pointerup', () => { drag = null; });
draw();
</script>
</body>
</html>
`;
const file = path.join(ROOT, 'artboards', outName + 'Mock.dc.html');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out);
console.log(path.relative(ROOT, file));
